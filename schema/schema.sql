CREATE TABLE project (
    id bigint PRIMARY KEY,
    name varchar(255),
    username varchar(255),
    avatar varchar(255),
    avatar_file_id varchar(255),
    is_template boolean NOT NULL DEFAULT false,
    deleted_at timestamptz
);

CREATE TABLE debug (
    id bigint PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES project (id),
    service_id varchar(255),
    status varchar(50) NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);

CREATE TABLE relase (
    id bigint PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES project (id),
    service_id varchar(255),
    status varchar(50) NOT NULL
);

CREATE TABLE enviroment (
    id bigint PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES project (id),
    key varchar(255) NOT NULL,
    value varchar(255) NOT NULL,
    secret boolean NOT NULL DEFAULT false
);

CREATE TABLE file (
    id bigint PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES project (id),
    file varchar(255) NOT NULL,
    filesize bigint,
    expires_at timestamptz
);

CREATE TABLE message (
    id bigint PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES project (id),
    caption text NOT NULL,
    message_type varchar(100) NOT NULL,
    file varchar(255),
    file_id varchar(255),
    button_type varchar(100) NOT NULL,
    buttons jsonb NOT NULL,
    total bigint NOT NULL DEFAULT 0,
    done bigint NOT NULL DEFAULT 0,
    fail bigint NOT NULL DEFAULT 0,
    status varchar(100) NOT NULL
);

CREATE TABLE collection (
    id bigint PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES project (id),
    name varchar(255) NOT NULL
);

CREATE TABLE api_projectresourcesnapshot (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES project (id),
    disk_bytes bigint NOT NULL DEFAULT 0,
    disk_files_bytes bigint NOT NULL DEFAULT 0,
    disk_cms_bytes bigint NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now()
);
